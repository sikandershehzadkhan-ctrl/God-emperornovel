import assert from "node:assert/strict";
import fs from "node:fs";
const app=fs.readFileSync("public/app.js","utf8");
const served=fs.readFileSync("public/app-17.23.0.js","utf8");
assert.equal(app,served,"canonical and served bundles must remain byte-identical");
const homeStart=app.indexOf("async function home()");
const readerStart=app.indexOf("async function reader()");
const readerEnd=app.indexOf("\nasync function ",readerStart+1);
assert.ok(homeStart>=0&&readerStart>homeStart,"homepage and reader route must exist");
const home=app.slice(homeStart,readerStart);
const reader=app.slice(readerStart,readerEnd>readerStart?readerEnd:undefined);
assert.doesNotMatch(home,/window\.addEventListener\(['"]online['"]/,"reader reconnect handler must not be registered in the homepage scope");
assert.match(reader,/window\.addEventListener\(['"]online['"],async\(\)=>/,"reader route must own its reconnect handler");
assert.match(reader,/const verifyProgressAccount=async\(\)=>/,"every recovery attempt must revalidate the signed-in identity");
assert.match(reader,/verifiedAccount!==progressAccount/,"recovery must reject a different active account");
assert.match(reader,/readerProgressConflictActions/,"reader must render conflict resolution actions");
assert.match(reader,/Keep this device/,"reader must offer explicit local-position retention");
assert.match(reader,/Use account progress/,"reader must offer explicit server-position retention");
assert.match(reader,/resolveReadingProgressConflict\('local'\)/,"local choice must have an explicit handler");
assert.match(reader,/resolveReadingProgressConflict\('account'\)/,"server choice must have an explicit handler");
assert.match(reader,/expected_revision:remoteRevision/,"local choice must use the latest server revision");
assert.match(reader,/if\(error.status===409\)\{progressConflict=true;progressSync='conflict'/,"a concurrent update during resolution must remain a conflict");
assert.match(reader,/readerStorage\.removeItem\(progressPendingKey\)/,"pending local progress is cleared only after a selected resolution succeeds");
assert.match(reader,/progressSync!=='conflict'/,"conflict actions must remain hidden outside conflict state");
const css=fs.readFileSync("public/imperial-design-system.css","utf8");
assert.match(css,/\.readerProgressConflictActions\[hidden\]\{display:none\}/,"hidden conflict actions must stay hidden");
assert.match(css,/\.readerProgressConflictActions button\{min-height:44px\}/,"conflict actions must meet mobile touch target size");
console.log("PASS: reader progress conflict recovery, identity verification, explicit resolution and served bundle parity.");
