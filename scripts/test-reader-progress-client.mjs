import assert from "node:assert/strict";
import fs from "node:fs";
const app=fs.readFileSync("public/app.js","utf8");
const release=fs.readFileSync("public/app-17.23.0.js","utf8");
assert.equal(app,release,"canonical and versioned application bundles must remain byte-identical");
assert.ok(app.includes("/api/reading-position?novel_id="),"reader must retrieve server progress");
assert.ok(app.includes("/api/reading-position',{method:'POST'"),"reader must save progress to the server");
assert.ok(app.includes("expected_revision:progressRevision"),"writes must use optimistic revision checks");
assert.ok(app.includes("setTimeout(()=>saveProgress"),"autosave must be debounced");
assert.ok(app.includes("window.addEventListener('online'"),"reader must reconcile when connectivity returns");
assert.ok(app.includes("readerProgress:'+id"),"local progress cache must remain available offline");
assert.ok(app.includes("if(!progressAccount||progressSync!=='synced')return"),"anonymous/offline sessions must not issue authenticated writes");
console.log("PASS: reader progress client uses server persistence, optimistic revisions, debounced autosave, offline cache and versioned bundle parity.");
