import assert from "node:assert/strict";
import fs from "node:fs";

const app=fs.readFileSync("public/app.js","utf8");
const served=fs.readFileSync("public/app-17.23.0.js","utf8");
const worker=fs.readFileSync("src/index.js","utf8");
const html=fs.readFileSync("public/index.html","utf8");
const start=app.indexOf("async function reader(){");
assert.ok(start>=0,"Reader route must exist");
const end=app.indexOf("\nasync function ",start+30);
assert.ok(end>start,"Reader route boundary must exist");
const reader=app.slice(start,end);
const handler=reader.indexOf("$('#bookmarkBtn').onclick=async()=>");
assert.ok(handler>=0,"Bookmark writes must be initiated by the explicit reader control");
assert.ok(reader.includes("api('/api/history',{method:'POST'"),"Opening an unlocked chapter must continue recording reading history");
assert.ok(!reader.includes("api('/api/bookmark',{method:'POST'"),"Opening a chapter must never silently create a bookmark");
assert.ok(reader.slice(handler).includes("method:bookmarked?'DELETE':'POST'"),"The explicit bookmark control must save and remove bookmarks");
assert.ok(reader.includes("localStorage.getItem('readerBookmark:'+id)"),"Guest bookmark state must be restored on the reader route");
assert.ok(reader.includes("localStorage.removeItem('readerBookmark:'+id)"),"Guest bookmark state must be removable");
assert.ok(reader.includes('aria-pressed="${bookmarked}"'),"Bookmark button must expose its initial pressed state");
assert.ok(reader.slice(handler).includes("setAttribute('aria-pressed',String(bookmarked))"),"Bookmark button must update its accessible pressed state");
const deleteStart=worker.indexOf('if(p==="/api/bookmark"&&m==="DELETE")');
assert.ok(deleteStart>=0,"Worker must expose bookmark removal");
const deleteEnd=worker.indexOf('if(p==="/api/reading-position"',deleteStart);
const removeRoute=worker.slice(deleteStart,deleteEnd);
assert.ok(removeRoute.includes("need(u)"),"Bookmark removal requires an authenticated session");
assert.ok(removeRoute.includes("parseReaderProgressTarget(await body(req))"),"Bookmark removal validates positive safe-integer targets");
assert.ok(removeRoute.includes("DELETE FROM bookmarks WHERE user_id=? AND novel_id=? AND chapter_number=?"),"Removal must be scoped to the session owner and selected chapter");
assert.ok(removeRoute.includes("bind(u.id,parsed.novelId,parsed.chapterNumber)"),"Client input must never choose the bookmark owner");
assert.ok(removeRoute.indexOf("parseReaderProgressTarget")<removeRoute.indexOf("DELETE FROM bookmarks"),"Invalid targets must be rejected before persistence");
assert.equal(app,served,"Served versioned application asset must match source app.js");
assert.ok(html.includes("/app-17.23.0.js"),"Public entry must load the synchronized versioned asset");
console.log("Reader bookmark intent passed: chapter visits record history only; explicit action toggles owner-scoped bookmarks; guest state and bundle parity verified.");
