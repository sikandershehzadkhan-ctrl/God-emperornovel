import fs from 'node:fs';
import assert from 'node:assert/strict';

const app = fs.readFileSync('public/app.js', 'utf8');
const served = fs.readFileSync('public/app-17.24.0.js', 'utf8');
const html = fs.readFileSync('public/index.html', 'utf8');
const start = app.indexOf('async function reader(){');
assert.ok(start >= 0, 'Reader route must exist');
const end = app.indexOf('\nasync function ', start + 30);
assert.ok(end > start, 'Reader route boundary must exist');
const reader = app.slice(start, end);
const bookmarkHandler = reader.indexOf("$('#bookmarkBtn').onclick=async()=>");
assert.ok(bookmarkHandler >= 0, 'Explicit bookmark control handler must exist');
const historyWrite = reader.indexOf("api('/api/history',{method:'POST'");
assert.ok(historyWrite >= 0, 'Opening an unlocked chapter must continue recording reading history');
assert.ok(!reader.includes("api('/api/bookmark',{method:'POST'"), 'Opening a chapter must never silently create a bookmark');
assert.ok(reader.slice(bookmarkHandler).includes("api('/api/bookmark',{method:now?'POST':'DELETE'"), 'Bookmark persistence and removal must occur from the explicit bookmark action');
assert.ok(reader.slice(bookmarkHandler).includes("method:now?'POST':'DELETE'"), 'Explicit bookmark control must save and remove bookmarks');
assert.ok(reader.includes("setAttribute('aria-pressed',String(bookmarked))"), 'Bookmark control must expose its initial state accessibly');
const server = fs.readFileSync('src/index.js', 'utf8');
assert.ok(server.includes('if(p==="/api/bookmark"&&m==="DELETE")'), 'Server must support bookmark removal');
assert.ok(server.includes('DELETE FROM bookmarks WHERE user_id=? AND novel_id=? AND chapter_number=?'), 'Bookmark removal must be scoped to the authenticated owner and selected chapter');
assert.ok(reader.slice(bookmarkHandler).includes("writeReaderSetting(key,num)"), 'Guest bookmark action must remain locally available through safe storage');
assert.ok(reader.includes("localStorage.getItem('readerBookmark:'+id)"), 'Guest bookmark state must be restored when the chapter is reopened');
assert.ok(reader.includes('const readReaderSetting='), 'Reader preferences must tolerate unavailable browser storage');
assert.ok(reader.includes('const writeReaderSetting='), 'Reader preference writes must tolerate unavailable browser storage');
assert.ok(reader.includes('Number.isFinite(sizeRaw)'), 'Stored font size must reject non-numeric values');
assert.ok(reader.includes("Math.min(30,Math.max(15,Math.round(sizeRaw)))"), 'Stored font size must be clamped to supported bounds');
assert.ok(reader.includes("['1.65','1.85','2'].includes"), 'Stored line spacing must be restricted to supported values');
assert.ok(reader.includes("['500','600','680'].includes"), 'Stored text width must be restricted to supported values');
assert.equal(app, served, 'Served versioned application asset must match source app.js');
assert.ok(html.includes('/app-17.24.0.js'), 'Public entry must load the synchronized versioned asset');
console.log('Reader bookmark intent passed: visits record history, bookmark writes require explicit action, guest behavior and source/served parity verified.');
