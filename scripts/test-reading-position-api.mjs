import assert from "node:assert/strict";
import fs from "node:fs";
const schema=fs.readFileSync("src/runtime-feature-schema.mjs","utf8");
const worker=fs.readFileSync("src/index.js","utf8");
assert.ok(schema.includes("runtime_feature_schema_version','2'"),"runtime schema must advance to v2");
assert.ok(schema.includes("CREATE TABLE IF NOT EXISTS reading_positions"),"reading positions table must be created idempotently");
assert.ok(schema.includes("PRIMARY KEY(user_id,novel_id)"),"one position per reader and novel");
assert.ok(schema.includes("CHECK(percent >= 0 AND percent <= 100)"),"percentage must be database-bounded");
const getAt=worker.indexOf('if(p==="/api/reading-position"&&m==="GET")');
const postAt=worker.indexOf('if(p==="/api/reading-position"&&m==="POST")');
const historyAt=worker.indexOf('if(p==="/api/history"&&m==="GET")');
assert.ok(getAt>=0&&postAt>getAt&&historyAt>postAt,"both reader-progress methods must be dispatched before history");
const get=worker.slice(getAt,postAt),post=worker.slice(postAt,historyAt);
assert.ok(get.includes("need(u)")&&get.includes("rp.user_id=?"),"GET must be authenticated and scoped to session owner");
assert.ok(post.includes("need(u)")&&post.includes("u.id"),"POST must be authenticated and derive owner from session");
assert.ok(post.includes("req.headers.get(\"origin\")!==url.origin"),"POST must reject cross-origin writes");
assert.ok(post.includes("consumeAuthRateLimit"),"POST must be rate-limited");
assert.ok(post.includes("expected_revision")&&post.includes("WHERE ?=0 ON CONFLICT")&&post.includes("WHERE reading_positions.revision=? RETURNING"),"initial inserts require revision zero and updates require exact optimistic revision");
assert.ok(post.includes("},409)"),"stale writes must return conflict");
assert.ok(post.includes("n.rights_status IN ('original','public_domain','licensed','authorized')"),"only rights-eligible novels may receive progress writes");
assert.ok(post.includes("c.publication_status='published' AND n.publication_status='published'"),"only published chapters may receive progress writes");
assert.ok(post.includes("WHERE user_id=? AND novel_id=?"),"conflict response must be scoped to the session owner");
console.log("PASS: reader progress schema, session ownership, rights/publication eligibility, CSRF, rate limit and optimistic concurrency.");
